// Проверка стиля статей про доступ (ru, en): фразы про свои усилия, взгляд со стороны, пояснения о происхождении мнения, голый текст после подзаголовка
import { readFileSync } from 'node:fs'

const files = [
  'content/blog/claude-code-access-regions-vpn-bans.md',
  'content/blog/claude-code-access-regions-vpn-bans.en.md',
  'content/blog/codex-access-regions-vpn-bans.md',
  'content/blog/codex-access-regions-vpn-bans.en.md',
  'content/blog/claude-code-install-and-price.md',
  'content/blog/claude-code-install-and-price.en.md',
  'content/blog/codex-or-chatgpt-what-to-choose.md',
  'content/blog/codex-or-chatgpt-what-to-choose.en.md',
]
const banned = [
  [/Устроено всё/i, 'пустая вводная фраза'],
  [/Я (открыл|открыла|сверил|сверила|прочитал|прочитала)[^.]{0,80}(18\.11\.2026|полностью|целиком)/, 'доказательство усердия'],
  [/не буду (это )?(домысливать|гадать)|гадать о них я не буду/, 'объявление об отказе'],
  [/придумыва\w+ (его|её|их|он[аио]?)[^.]{0,20}не буду|I will not (invent|guess)/i, 'объявление об отказе'],
  [/Я (открыл|открыла)[^.]{0,60}разобрал|I opened[^.]{0,60}(went through|read) (it )?(in full|fully)/i, 'доказательство усердия'],
  [/(чаще всего|часто) ошибаются|people (most often|often) (get|go) wrong/i, 'взгляд со стороны'],
  [/(моя|мо[её]) (классификация|мнение|оценка)[^.]{0,60}(не служит|не цитата)|my own classification/i, 'пояснение о происхождении мнения'],
  [/Я сверил очень много|Я перепроверил всё/i, 'счёт усилий'],
  [/с оговоркой в скобках/i, 'непонятная отсылка'],
  [/ошибки читателя|ошибка читателя|reader.s mistake/i, 'разговор о читателе со стороны'],
  [/\bI (opened|read|went through|compared|checked|found no|do not suggest|will not)\b|pages I read/, 'рассказ о собственных усилиях (en)'],
  [/\bя (в тексте |на странице |в документах )?(не нашёл|проверил|сверил|искал)|проверенных мной|моей сверки|кому (она|он|оно) принадлежит|ему принадлежит/i, 'рассказ о собственных усилиях или неверное «принадлежит»'],
  [/Многие думают|Many people think/i, 'шаблон подряд'],
  [/[Сс]траниц[аыуе]\s+(политики\s+|списка\s+|отказа карты\s+|ZDR\s+)?(не\s+)?(говорит|называет|объясняет|молчит|даёт|описывает|пишет|указывает|показывает|приводит|перечисляет|сообщает|раскрывает)|страницы\s+(Anthropic\s+)?(не\s+)?(описывают|объясняют|называют)/, 'документ как говорящий: писать «Anthropic не объясняет», «в политике сказано»'],
  [/сидеть|сидит|сидели/, 'разговорное «сидеть» про место или работу: «находится», «работает»'],
  [/(^|[ .])(Минута|Две минуты|Пять минут): |Десять минут хватает/, 'телеграфный счёт минут: связным текстом'],
  [/Забыть про владение|схем[уы] владения|о владении|владение сработал|или про владение|и владение\b/, 'владение без объекта: «кто владеет компанией», «собственники компании»'],
  [/[Сс]лов[аоу]?\s+«?VPN|слов[ао]\s+VPN|\bя\s+(не\s+)?(нашёл|нашла|просмотрел|разбирал)\b/, 'слово «VPN» вместо «VPN не упомянут» или рассказ об усилиях'],
  [/юридическим английским|каждое слово там значит/, 'пояснение очевидного'],
  [/разобран[оы]? в разделе|см\. (выше|ниже)|described in the section/i, 'отсылка к разделу'],
]
let bad = 0
for (const f of files) {
  const lines = readFileSync(f, 'utf8').split('\n')
  lines.forEach((l, i) => {
    for (const [re, why] of banned) if (re.test(l)) { console.log(`${f}:${i + 1}: ${why}: ${l.trim().slice(0, 110)}`); bad++ }
    const t = l.trim(), p = (lines[i - 1] || '').trim()
    if (t && !t.startsWith('<') && p && p.endsWith('>') && !/^<(th|td|tr)/.test(p) && !p.startsWith('---') && !/(copy>|<b-codebox[^>]*>)$/.test(p)) {
      console.log(`${f}:${i + 1}: голый текст сразу после тега (нужна пустая строка)`); bad++
    }
  })
}
console.log(bad ? `check-blog-style: нарушений ${bad}` : 'check-blog-style: ок')
process.exit(bad ? 1 : 0)
